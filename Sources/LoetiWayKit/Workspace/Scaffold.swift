import Foundation

/// Files and snippets `lw init` writes or prints.
public enum Scaffold {
    /// Host variable name. It must not be `GH_TOKEN` on the host, or it would override the
    /// user's own `gh` login there.
    public static let githubVariable = "ASYLUM_GH_TOKEN"

    public static func configTemplate(customer: String, githubOwner: String?) -> String {
        let name = yamlQuoted(customer)
        let vault = VaultNaming.agentVault(customer: customer)
        var text = """
        # lw (loeti-way): Proton-Pass-Agent und GitHub-PAT für \(customer)
        customer: \(name)

        proton:
          # agent: asylum-\(Slug.make(customer))     # Standard
          expiration: 3m                # 1w, 1m, 3m, 6m, 1y
          vaults:                       # nur agent-…-Vaults, siehe README
            - name: \(vault)
              role: viewer              # viewer, editor, manager
            # - name: \(vault)-infra
            #   role: viewer

        # env:                          # lw env liest die Werte mit dem Agent und setzt sie als Variablen
        #   MAVEN_PASSWORD: pass://\(vault)/Maven/password

        """
        if let githubOwner {
            text += """
            github:
              owner: \(yamlQuoted(githubOwner))      # Organisation oder Benutzer, dem die Repos gehören
              expires_in_days: 90
              repositories: []              # Erinnerung für "Only select repositories"
              permissions:
                contents: write
                pull_requests: write

            """
        } else {
            text += """
            # github:
            #   owner: org-des-kunden
            #   expires_in_days: 90
            #   repositories: []
            #   permissions:
            #     contents: write
            #     pull_requests: write

            """
        }
        return text
    }

    /// The same for customer and project folders: `lw env` decides from the folder what to load.
    /// No secrets and no references in the file, so an agent editing it learns nothing.
    public static let envrc = """
    # Generated by lw (loeti-way). No secrets here: lw env reads them from Proton Pass with the
    # host agent and prints the exports. Asylum passes them on (env-from-host).
    if has lw; then
      eval "$(lw env)"
    else
      log_error "lw fehlt im PATH: Tokens nicht geladen"
    fi

    """

    /// `owner` is always written, so the project keeps working when the customer's `github`
    /// section changes or goes away.
    public static func projectTemplate(project: String, customer: CustomerConfig, githubOwner: String?) -> String {
        let owner = githubOwner ?? customer.github?.owner ?? "org"
        let ownerLine = "  owner: \(yamlQuoted(owner))      # Organisation oder Benutzer, dem das Repo gehört"
        return """
        # lw (loeti-way): eigener GitHub-PAT für \(project) (Kunde \(customer.customer)).
        # Gilt in diesem Ordner statt des PAT des Kunden. Der Proton-Agent bleibt der des Kunden.
        # Der Projektname ist immer der Ordnername.

        github:
        \(ownerLine)
          # token_name: \(yamlQuoted("\(customer.customer)_\(project)_PAT"))   # Name des Tokens auf GitHub
          repositories: [\(yamlQuoted(project))]    # Erinnerung für "Only select repositories"
          # expires_in_days und permissions: Standard wie beim Kunden

        """
    }

    /// Files `lw init --project` writes into a project folder; they stay out of its git repo.
    public static let projectFiles = [ProjectConfig.fileName, ".envrc"]

    /// Adds `entries` to `.git/info/exclude` if `folder` is a git repository. Returns the added ones.
    public static func excludeFromGit(_ entries: [String], in folder: URL) throws -> [String] {
        let gitDir = folder.appendingPathComponent(".git")
        var isDirectory: ObjCBool = false
        guard FileManager.default.fileExists(atPath: gitDir.path, isDirectory: &isDirectory), isDirectory.boolValue else {
            return []
        }
        let exclude = gitDir.appendingPathComponent("info/exclude")
        let existing = (try? String(contentsOf: exclude, encoding: .utf8)) ?? ""
        let present = Set(existing.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) })
        let missing = entries.filter { !present.contains($0) && !present.contains("/" + $0) }
        guard !missing.isEmpty else { return [] }
        var text = existing
        if !text.isEmpty && !text.hasSuffix("\n") { text += "\n" }
        text += "# lw (loeti-way)\n" + missing.map { "/" + $0 + "\n" }.joined()
        try FileManager.default.createDirectory(at: exclude.deletingLastPathComponent(), withIntermediateDirectories: true)
        try text.write(to: exclude, atomically: true, encoding: .utf8)
        return missing
    }

    /// No Proton token goes into a container: pass-cli isn't there, values from `env` arrive
    /// as plain variables. Variables that aren't set on the host are skipped by Asylum.
    public static func asylumConfigSnippet(env names: [String] = []) -> String {
        (["# ~/.asylum/config.yaml (gilt für alle Kunden; nicht gesetzte Variablen überspringt Asylum)",
          "env-from-host:",
          "  GH_TOKEN: \(githubVariable)"]
            + names.map { "  \($0): \(EnvNaming.hostVariable($0))" }).joined(separator: "\n")
    }

    public static let restartHint = """
    Damit Container den neuen Token bekommen:
      1. In offenen Shells im Kunden- bzw. Projektordner: direnv reload
      2. Alle Asylum-Sitzungen des Kunden beenden und neu starten (der Token gilt ab Erstellung des Containers)
    """

    static func yamlQuoted(_ text: String) -> String {
        let plain = text.allSatisfy { $0.isLetter || $0.isNumber || $0 == " " || $0 == "-" || $0 == "_" || $0 == "." }
        if plain, let first = text.first, first.isLetter { return text }
        let escaped = text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        return "\"\(escaped)\""
    }
}
